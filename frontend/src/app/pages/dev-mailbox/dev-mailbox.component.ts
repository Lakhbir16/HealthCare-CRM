export class DevMailboxComponent implements OnInit {
  messages: DevMailMessage[] = [];
  filteredMessages: DevMailMessage[] = [];
  searchFilter = '';
  isLoading = false;
  copiedText = '';

  constructor(
    private apiService: ApiService,
    private cdr: ChangeDetectorRef
  ) {}

  ngOnInit(): void {
    this.loadMessages();
  }

  loadMessages(): void {
    this.isLoading = true;
    this.cdr.detectChanges();
    this.apiService.getDevMailboxMessages().subscribe({
      next: (res) => {
        this.isLoading = false;
        this.messages = (res as any)?.data ?? (res as any)?.Data ?? [];
        this.applyFilter();
        this.cdr.detectChanges();
      },
      error: () => {
        this.isLoading = false;
        this.cdr.detectChanges();
      }
    });
  }

  onFilterChange(): void {
    this.applyFilter();
    this.cdr.detectChanges();
  }

  applyFilter(): void {
    if (!this.searchFilter.trim()) {
      this.filteredMessages = [...this.messages];
    } else {
      const q = this.searchFilter.trim().toLowerCase();
      this.filteredMessages = this.messages.filter(m =>
        m.recipientEmail.toLowerCase().includes(q) ||
        m.content.toLowerCase().includes(q) ||
        m.subject.toLowerCase().includes(q)
      );
    }
  }

  copyOtp(otp: string): void {
    navigator.clipboard.writeText(otp);
    this.copiedText = otp;
    this.cdr.detectChanges();
    setTimeout(() => {
      this.copiedText = '';
      this.cdr.detectChanges();
    }, 3000);
  }
}
